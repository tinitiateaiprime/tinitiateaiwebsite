    await page.getByRole('button', { name: 'Toggle menu' }).click()
    const navigation = page.locator('#mobile-navigation')
    await expect(navigation.getByRole('link', { name: 'My Dashboard' })).toBeVisible()
    await expect(navigation.getByRole('link', { name: 'Student Profile' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/ux-student-mobile.png', fullPage: true })
