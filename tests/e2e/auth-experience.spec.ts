test('student login immediately changes navigation, shows licensed learning and logout revokes stale tickets', async ({ page }) => {
  test.setTimeout(180000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await signIn(page); await dismiss(page)
  const me = (await (await page.request.get('/api/students/me')).json()).user
  await expect(page.getByRole('heading', { name: `Welcome back, ${me.name}` })).toBeVisible()
  await expect(page.getByText(me.email, { exact: true })).toBeVisible()
  const header = page.getByRole('banner')
  await expect(header.getByRole('link', { name: 'Student Login' })).toHaveCount(0)
  await expect(header.getByText(me.name, { exact: true })).toBeVisible()
  await expect(header.getByRole('link', { name: 'My Learning', exact: true })).toBeVisible()
  const licenses = (await (await page.request.get('/api/course-licenses?limit=100&depth=0')).json()).docs
  const activeIDs = new Set<number>(licenses.filter((row: { status: string; startsAt?: string; expiresAt?: string }) => row.status === 'active' && (!row.startsAt || Date.parse(row.startsAt) <= Date.now()) && (!row.expiresAt || Date.parse(row.expiresAt) > Date.now())).flatMap((row: { courses: number[] }) => row.courses))
  await expect(page.locator('[data-course-id]')).toHaveCount(activeIDs.size)
  expect(new Set(await page.locator('[data-course-id]').evaluateAll(nodes => nodes.map(node => Number(node.getAttribute('data-course-id')))))).toEqual(activeIDs)
  const visibleMetadata = (await (await page.request.get('/api/academy-lessons?limit=200&depth=0')).json()).docs
  expect(visibleMetadata.every((row: { course: number; kind: string; publicDemo: boolean }) => activeIDs.has(row.course) || row.kind === 'demo' && row.publicDemo)).toBe(true)
  // Existing local grants may have been revoked manually; verify their actual state.
  if (licenses.some((row: { status: string; expiresAt?: string }) => row.status !== 'revoked' && row.expiresAt && Date.parse(row.expiresAt) <= Date.now())) await expect(page.getByText('Expired', { exact: true }).first()).toBeVisible()
  if (licenses.some((row: { status: string }) => row.status === 'revoked')) await expect(page.getByText('Revoked', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: 'test-results/ux-student-dashboard.png', fullPage: true })
  const python = (await (await page.request.get(`/api/academy-lessons?where[key][equals]=${print}&depth=0`)).json()).docs[0]
  const continuation = page.locator(`[data-course-id="${python.course}"]`).getByRole('link', { name: /^Continue Learning/ })
  await expect(continuation).toHaveAttribute('href', /\/academy\/lessons\/foundational-python-/)
  await continuation.click()
  const frame = page.frameLocator('iframe')
  await expect(frame.locator('#py-stage')).toBeVisible()
  await expect(frame.locator('#lesson-video video')).toHaveCount(1)
  await frame.locator('#lesson-video video').evaluate(async node => { const video = node as HTMLVideoElement; video.muted = true; await video.play() })
  await expect.poll(() => frame.locator('#lesson-video video').evaluate(node => (node as HTMLVideoElement).currentTime)).toBeGreaterThan(0.1)
  const ticketURL = (await page.locator('iframe').getAttribute('src'))!
  await header.getByRole('link', { name: 'My Learning', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'My Learning', exact: true })).toBeVisible()
  await expect(page.locator('a[href="/academy/lessons/snowflake-dataengineering-tables"]')).toHaveCount(0)
  await header.getByRole('button', { name: 'Logout', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?loggedOut=1/)
  await expect(page.getByRole('banner').getByRole('link', { name: 'Student Login' })).toBeVisible()
  expect((await page.request.get(ticketURL)).status()).toBe(403)
  expect((await page.request.get(`/api/academy/video/${print}`)).status()).toBe(403)
  await page.goBack(); await expect(page.getByRole('heading', { name: 'My Learning', exact: true })).toHaveCount(0)
  await page.goto('/dashboard'); await expect(page).toHaveURL(/\/login/)
})

