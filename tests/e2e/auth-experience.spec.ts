test('switching student accounts revokes the replaced session and removes the other learners cached lesson', async ({ page, context }) => {
  test.setTimeout(180000)
  await signIn(page)
  await page.goto('/academy/lessons/foundational-python-variables'); await dismiss(page)
  await expect(page.frameLocator('iframe').locator('#py-stage')).toBeVisible()
  const oldTicket = (await page.locator('iframe').getAttribute('src'))!
  const other = await context.newPage()
  await signIn(other, 'academy-unlicensed@example.test'); await dismiss(other)
  await expect(other.getByRole('heading', { name: 'No licensed courses yet' })).toBeVisible()
  expect((await other.request.get(oldTicket)).status()).toBe(403)
  await page.bringToFront()
  await expect(page.locator('iframe')).toHaveCount(0)
  const me = (await (await page.request.get('/api/students/me')).json()).user
  expect(me.email).toBe('academy-unlicensed@example.test')
  await page.goto('/dashboard'); await dismiss(page)
  await expect(page.getByText('academy-unlicensed@example.test', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /^Continue Learning/ })).toHaveCount(0)
  await other.close()
})
