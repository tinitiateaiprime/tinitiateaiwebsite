import { test, expect, type Page } from '@playwright/test'

const password = 'Phase1-Local-Verification-Only!'
const print = 'foundational-python-print'
async function dismiss(page: Page) { await page.getByRole('button', { name: 'Close promotion' }).click({ timeout: 1200 }).catch(() => {}) }
async function signIn(page: Page, email = 'phase1-student@example.test', trainer = false) {
  await page.goto(trainer ? '/login?mode=trainer' : '/login')
  await dismiss(page)
  if (trainer) await expect(page.getByRole('link', { name: 'Sign up', exact: true })).toHaveCount(0)
  await page.locator('input[name=email]').fill(email)
  await page.locator('input[name=password]').fill(password)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page).toHaveURL(trainer ? /\/trainer$/ : /\/dashboard$/)
}
async function adminSignIn(page: Page) {
  await page.goto('/admin/login')
  await page.locator('input[name=email]').fill('phase1-admin@example.test')
  await page.locator('input[name=password]').fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page).toHaveURL(/\/admin$/)
  await expect(page.getByRole('button', { name: 'Logout', exact: true })).toBeVisible()
}

