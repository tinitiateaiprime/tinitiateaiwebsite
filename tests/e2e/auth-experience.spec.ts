test('CMS logout uses Users even after a student signs in in another tab, without ending the student session', async ({ page, context }) => {
  test.setTimeout(180000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await adminSignIn(page)
  await page.screenshot({ path: 'test-results/ux-admin-logout.png', fullPage: true })
  const student = await context.newPage()
  await signIn(student)
  await page.bringToFront()
  const outgoing = page.waitForResponse(response => response.url().endsWith('/api/users/logout') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Logout', exact: true }).click()
  const response = await outgoing
  expect(response.status()).toBe(200)
  await expect(page).toHaveURL(/\/admin\/login$/)
  await expect(page.getByText('Incorrect collection', { exact: true })).toHaveCount(0)
  await student.bringToFront(); await student.goto('/dashboard'); await dismiss(student)
  await expect(student.getByRole('heading', { name: /Welcome back,/ })).toBeVisible()
  expect((await (await student.request.get('/api/students/me')).json()).user.collection).toBe('students')
  expect((await (await page.request.get('/api/users/me')).json()).user).toBeNull()
  await page.goto('/admin'); await expect(page).toHaveURL(/\/admin\/login/)
  await student.close()
})

